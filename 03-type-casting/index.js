// konversi tipe data ke tipe data yang lain
// typecasting secara implisit (terjadi secara otomatis ketika compiler / runtime dijalankan);
const example = "satu" + 1;
console.log(example); // output: satu1

// typecasting secara eksplisit (dilakukan secara manual oleh programmer);
const satu = Number("1");
console.log(satu);
